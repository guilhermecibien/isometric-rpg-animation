"""Build the procedural demo character: atlas PNG/JSON + character-manifest.json."""
from __future__ import annotations

from pathlib import Path

from PIL import Image

from . import procedural as P
from .analyze import dominant_colors
from .atlas import write_atlas
from .common import DIRECTIONS_8, frame_name, write_json
from .manifest import SCHEMA_VERSION


def generate_character(out_dir: str | Path, char_id: str = "hero", only: list[str] | None = None) -> Path:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    frames: dict[str, Image.Image] = {}
    animations: dict = {}
    for spec in P.available_animations(only):
        entry: dict = {
            "frames": spec.frames, "fps": spec.fps, "loop": spec.loop, "directions": list(DIRECTIONS_8),
            "events": [{"frame": f, "name": n} for f, n in spec.events],
        }
        travel, markers = {}, {}
        for d in DIRECTIONS_8:
            imgs, feet = P.render_animation(spec, d)
            for i, im in enumerate(imgs):
                frames[frame_name(spec.key, d, i)] = im
            if spec.stride:
                travel[d] = P.cycle_travel(spec.stride, d)
                markers[d] = feet
            elif spec.key in ("idle", "start_walk", "stop_walk", "attack", "cast", "hit", "death"):
                markers[d] = feet  # kept for debug overlays; no travel → not slide-checked
        if travel:
            entry["cycleTravel"] = travel
        if markers:
            entry["footMarkers"] = markers
        animations[spec.key] = entry

    atlas_png, atlas_json = out / f"{char_id}.png", out / f"{char_id}.json"
    write_atlas(frames, atlas_png, atlas_json, columns=16)
    sample = frames[frame_name("idle", "S", 0)]
    manifest = {
        "schemaVersion": SCHEMA_VERSION,
        "id": char_id,
        "name": "Procedural Hero",
        "profile": "humanoid",
        "frame": {"width": P.FRAME_W, "height": P.FRAME_H},
        "pivot": {"x": P.PIVOT[0], "y": P.PIVOT[1]},
        "shadow": {"rx": 17, "ry": 8.5},
        "atlas": {"image": atlas_png.name, "data": atlas_json.name},
        "animations": animations,
        "source": {
            "method": "procedural",
            "generator": "isoanim.procedural (3D skeleton → isometric projection)",
            "license": "MIT (generated by this repository; no third-party art)",
            "projection": {"tileWidth": P.TILE_W, "tileHeight": P.TILE_H, "zScale": P.Z_SCALE, "cameraRotation": 0},
        },
        "analysis": {
            "analyzedBy": "generator-ground-truth",
            "semanticAnalysis": False,
            "dominantColors": dominant_colors(sample),
            "invariants": ["pivot fixed at ground point", "tunic teal, pants indigo, hair brown in every frame", "sword in right hand"],
            "notes": "Feet positions in footMarkers are exact (taken from the 3D rig), so slide validation is meaningful for this asset.",
        },
    }
    mpath = out / "character-manifest.json"
    write_json(mpath, manifest)
    return mpath
